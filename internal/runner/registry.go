package runner

import (
	"errors"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

// prepareRegistry adds one public package shared by every instrumented package
// and every generated TestMain. Keeping it outside internal directories allows
// instrumented dependencies in other modules to register their exporters.
func prepareRegistry(packages []listedPackage, tempDir string, overlay map[string]string) (string, error) {
	var module *listedModule
	for _, pkg := range packages {
		if pkg.Standard || pkg.Goroot || isVendor(pkg.Dir) || pkg.Module == nil {
			continue
		}
		if module == nil || pkg.Module.Main {
			module = pkg.Module
		}
		if module.Main {
			break
		}
	}
	if module == nil || module.Path == "" || module.Dir == "" {
		return "", errors.New("cover: coverage runtime requires module mode (GOPATH packages are not supported)")
	}
	var child string
	for {
		prefix, err := uniquePrefix(nil)
		if err != nil {
			return "", err
		}
		child = "coverruntime_" + strings.TrimPrefix(prefix, "__cover_")
		if _, err := os.Lstat(filepath.Join(module.Dir, child)); errors.Is(err, os.ErrNotExist) {
			break
		} else if err != nil {
			return "", fmt.Errorf("check registry directory: %w", err)
		}
	}
	src, err := registrySource()
	if err != nil {
		return "", err
	}
	backing := filepath.Join(tempDir, "registry.go")
	if err := os.WriteFile(backing, src, 0600); err != nil {
		return "", fmt.Errorf("write coverage registry: %w", err)
	}
	overlay[filepath.Join(module.Dir, child, "registry.go")] = backing
	return strings.TrimSuffix(module.Path, "/") + "/" + child, nil
}

func registrySource() ([]byte, error) {
	src, err := format.Source([]byte(`// Code generated by cover; DO NOT EDIT.
package coverruntime

import (
	"errors"
	"fmt"
	"os"
	"sync"
)

var registrationMu sync.Mutex
var saveMu sync.Mutex
var exporters []func() error

func Register(exporter func() error) {
	registrationMu.Lock()
	exporters = append(exporters, exporter)
	registrationMu.Unlock()
}

func save() error {
	saveMu.Lock()
	defer saveMu.Unlock()
	registrationMu.Lock()
	callbacks := append([]func() error(nil), exporters...)
	registrationMu.Unlock()
	var errs []error
	for _, callback := range callbacks {
		if err := callback(); err != nil {
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}

// Finish saves every instrumented package loaded by this binary.
func Finish(code int) int {
	if err := save(); err != nil {
		fmt.Fprintln(os.Stderr, "cover: save counters:", err)
		return 2
	}
	return code
}

// Exit preserves the execution time of direct, deferred, and goroutine exits.
func Exit(exit func(int), code int) {
	exit(Finish(code))
}

// Flush also handles a TestMain that returns without explicitly exiting.
func Flush() {
	if Finish(0) != 0 {
		os.Exit(2)
	}
}
`))
	if err != nil {
		return nil, fmt.Errorf("format coverage registry: %w", err)
	}
	return src, nil
}
