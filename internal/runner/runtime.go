package runner

import (
	"fmt"
	"go/format"
)

// runtimeSource returns a standalone, per-package runtime. The mapping must be a
// variable initializer, not an init function: Go's initialization dependency
// analysis then initializes it before any original global initializer that
// calls an instrumented function, even when that function is in an earlier file.
func runtimeSource(packageName, prefix, countFile string, size int) ([]byte, error) {
	src := fmt.Sprintf(`// Code generated by cover; DO NOT EDIT.
package %s

import (
	%[2]sOS "os"
	%[2]sSyscall "syscall"
	%[2]sAtomic "sync/atomic"
	%[2]sUnsafe "unsafe"
)

var %[2]sMapping = %[2]sSetup()

func %[2]sSetup() []byte {
	f, err := %[2]sOS.OpenFile(%[3]q, %[2]sOS.O_RDWR, 0)
	if err != nil {
		panic("cover: open shared counters: " + err.Error())
	}
	defer f.Close()
	mapping, err := %[2]sSyscall.Mmap(int(f.Fd()), 0, %[4]d,
		%[2]sSyscall.PROT_READ | %[2]sSyscall.PROT_WRITE, %[2]sSyscall.MAP_SHARED)
	if err != nil {
		panic("cover: mmap shared counters: " + err.Error())
	}
	return mapping
}

func %[2]sHit(counter int) {
	%[2]sAtomic.AddUint64((*uint64)(%[2]sUnsafe.Pointer(&%[2]sMapping[counter * 8])), 1)
}

func %[2]sBool[%[2]sT ~bool](trueCounter, falseCounter int, value %[2]sT) %[2]sT {
	if value {
		%[2]sHit(trueCounter)
	} else {
		%[2]sHit(falseCounter)
	}
	return value
}
`, packageName, prefix, countFile, size)
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("format coverage runtime: %w", err)
	}
	return formatted, nil
}
