package main

import (
	"fmt"
	"go/format"
)

// runtimeSource returns a per-package runtime backed by ordinary Go atomics.
// Counters have no initializer, so instrumented global initializers can safely
// increment them before this file's init function registers the exporter.
func runtimeSource(packageName, prefix, countDir, registryImport string, count int) ([]byte, error) {
	src := fmt.Sprintf(`// Code generated by cover; DO NOT EDIT.
package %s

import (
	%[2]sJSON "encoding/json"
	%[2]sOS "os"
	%[2]sPath "path/filepath"
	%[2]sStrconv "strconv"
	%[2]sAtomic "sync/atomic"
	%[2]sRegistry %[4]q
)

var %[2]sCounters [%[5]d]%[2]sAtomic.Uint64

func init() {
	%[2]sRegistry.Register(%[2]sSave)
}

func %[2]sHit(counter int) {
	%[2]sCounters[counter].Add(1)
}

func %[2]sBool[%[2]sT ~bool](trueCounter, falseCounter int, value %[2]sT) %[2]sT {
	if value {
		%[2]sHit(trueCounter)
	} else {
		%[2]sHit(falseCounter)
	}
	return value
}

func %[2]sSave() error {
	var snapshot [%[5]d]uint64
	for i := range snapshot {
		snapshot[i] = %[2]sCounters[i].Load()
	}
	f, err := %[2]sOS.CreateTemp(%[3]q, ".snapshot-*")
	if err != nil {
		return err
	}
	defer %[2]sOS.Remove(f.Name())
	if err := %[2]sJSON.NewEncoder(f).Encode(snapshot); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	// Finish and Flush may both run. Replacing the process's snapshot avoids
	// counting its earlier snapshot twice when the runner merges the files.
	name := %[2]sPath.Join(%[3]q, %[2]sStrconv.Itoa(%[2]sOS.Getpid()) + ".json")
	return %[2]sOS.Rename(f.Name(), name)
}
`, packageName, prefix, countDir, registryImport, count)
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("format coverage runtime: %w", err)
	}
	return formatted, nil
}
