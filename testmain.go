// prepareTestMain adds a normal-completion save path to every tested package.
// Both existing test packages are considered: Go permits TestMain in either the
// package under test or its external (package_test) test package.
func prepareTestMain(pkg listedPackage, prefix, registryImport, tempDir string, number int, overlay map[string]string) error {
	files := append(append([]string(nil), pkg.TestGoFiles...), pkg.XTestGoFiles...)
	found := false
	for i, name := range files {
		filename := filepath.Join(pkg.Dir, name)
		src, err := os.ReadFile(filename)
		if err != nil {
			return fmt.Errorf("read test source %s: %w", filename, err)
		}
		rewritten, hasMain, err := rewriteTestMain(filename, src, prefix+"TestRuntime", registryImport)
		if err != nil {
			return err
		}
		if !hasMain {
			continue
		}
		if found {
			return fmt.Errorf("cover: multiple TestMain functions in %s", pkg.ImportPath)
		}
		found = true
		backing := filepath.Join(tempDir, fmt.Sprintf("pkg%d_%s_testmain%d.go", number, prefix, i))
		if err := os.WriteFile(backing, rewritten, 0600); err != nil {
			return fmt.Errorf("write rewritten TestMain: %w", err)
		}
		overlay[filename] = backing
	}
	if found {
		return nil
	}
	// TestMain(*testing.T) is an ordinary test, not the harness hook. Keep its
	// name (and hence -run behavior) intact by using the other test namespace.
	// Production declarations share the internal test package's namespace too.
	internal := append(append(append([]string(nil), pkg.GoFiles...), pkg.CgoFiles...), pkg.TestGoFiles...)
	occupied, err := declaresTestMain(pkg.Dir, internal)
	if err != nil {
		return err
	}
	packageName := pkg.Name
	if occupied {
		externalOccupied, err := declaresTestMain(pkg.Dir, pkg.XTestGoFiles)
		if err != nil {
			return err
		}
		if externalOccupied {
			return fmt.Errorf("cover: unsupported TestMain declarations in %s: both %s and %s_test declare TestMain without a TestMain(*testing.M) hook; cannot add a coverage-saving hook without renaming existing declarations", pkg.ImportPath, pkg.Name, pkg.Name)
		}
		packageName += "_test"
	}
	src, err := testMainSource(packageName, prefix, registryImport)
	if err != nil {
		return err
	}
	virtual, err := testMainPath(pkg.Dir, "zz"+prefix+"_testmain_test.go", overlay)
	if err != nil {
		return err
	}
	backing := filepath.Join(tempDir, fmt.Sprintf("pkg%d_%s_testmain.go", number, prefix))
	if err := os.WriteFile(backing, src, 0600); err != nil {
		return fmt.Errorf("write generated TestMain: %w", err)
	}
	overlay[virtual] = backing
	return nil
}

// declaresTestMain checks only active source files supplied by go list. Methods
// and local declarations do not occupy the package-level TestMain name.
func declaresTestMain(dir string, files []string) (bool, error) {
	for _, name := range files {
		filename := filepath.Join(dir, name)
		f, err := parser.ParseFile(token.NewFileSet(), filename, nil, parser.AllErrors)
		if err != nil {
			return false, fmt.Errorf("parse source %s: %w", filename, err)
		}
		for _, decl := range f.Decls {
			switch decl := decl.(type) {
			case *ast.FuncDecl:
				if decl.Recv == nil && decl.Name.Name == "TestMain" {
					return true, nil
				}
			case *ast.GenDecl:
				for _, spec := range decl.Specs {
					switch spec := spec.(type) {
					case *ast.TypeSpec:
						if spec.Name.Name == "TestMain" {
							return true, nil
						}
					case *ast.ValueSpec:
						for _, name := range spec.Names {
							if name.Name == "TestMain" {
								return true, nil
							}
						}
					}
				}
			}
		}
	}
	return false, nil
}

func testMainPath(dir, name string, overlay map[string]string) (string, error) {
	for {
		path := filepath.Join(dir, name)
		if _, ok := overlay[path]; !ok {
			if _, err := os.Lstat(path); os.IsNotExist(err) {
				return path, nil
			} else if err != nil {
				return "", fmt.Errorf("check TestMain filename: %w", err)
			}
		}
		name = strings.TrimSuffix(name, "_test.go") + "_x_test.go"
	}
}

func testMainSource(packageName, prefix, registryImport string) ([]byte, error) {
	src := fmt.Sprintf(`// Code generated by cover; DO NOT EDIT.
package %s
import (
 %[2]sOS "os"
 %[2]sTesting "testing"
 %[2]sRuntime %[3]q
)
func TestMain(m *%[2]sTesting.M) {
 %[2]sOS.Exit(%[2]sRuntime.Finish(m.Run()))
}
`, packageName, prefix, registryImport)
	out, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("generate TestMain: %w", err)
	}
	return out, nil
}

type testMainEdit struct {
	start, end int
	text       string
}

// rewriteTestMain leaves original test behavior intact while saving on normal
// return and recognized os.Exit calls. Imports are resolved lexically so aliases
// and dot imports work, without rewriting unrelated shadowing identifiers.
func rewriteTestMain(filename string, src []byte, alias, registryImport string) ([]byte, bool, error) {
	fs := token.NewFileSet()
	f, err := parser.ParseFile(fs, filename, src, parser.ParseComments|parser.AllErrors)
	if err != nil {
		return nil, false, fmt.Errorf("parse test source: %w", err)
	}
	var main *ast.FuncDecl
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv != nil || fn.Name.Name != "TestMain" {
			continue
		}
		// Match cmd/go/internal/load/test.go: it first accepts *T as an
		// ordinary test, then checks for the *M harness signature. This is a
		// syntactic check, deliberately independent of import/type resolution.
		if hasTestMainSignature(fn, "T") {
			continue
		}
		if !hasTestMainSignature(fn, "M") {
			return nil, false, fmt.Errorf("%s: wrong signature for TestMain, must be func TestMain(m *testing.M)", filename)
		}
		if fn.Type.TypeParams.NumFields() > 0 {
			return nil, false, fmt.Errorf("%s: TestMain cannot have type parameters", filename)
		}
		if main != nil {
			return nil, false, fmt.Errorf("%s: multiple TestMain functions", filename)
		}
		if fn.Body == nil {
			return nil, false, fmt.Errorf("%s: TestMain has no Go body to instrument", filename)
		}
		main = fn
	}
	if main == nil {
		return src, false, nil
	}
	imports := make(map[string]bool)
	dotOS := false
	for _, spec := range f.Imports {
		path, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			return nil, false, fmt.Errorf("%s: invalid import path: %w", filename, err)
		}
		if path != "os" {
			continue
		}
		name := "os"
		if spec.Name != nil {
			name = spec.Name.Name
		}
		if name == "." {
			dotOS = true
		} else if name != "_" {
			imports[name] = true
		}
	}
	file := fs.File(f.Pos())
	var edits []testMainEdit
	insert := func(p token.Pos, text string) {
		offset := file.Offset(p)
		edits = append(edits, testMainEdit{offset, offset, text})
	}
	// Reuse the original package clause's terminator for the new import. Adding
	// another trailing semicolon would create an invalid empty declaration when
	// the source spells its package semicolon explicitly.
	insert(f.Name.End(), ";import "+alias+" "+strconv.Quote(registryImport))
	// Register this first so all original defers run before a normal-return save.
	insert(main.Body.Lbrace+1, "defer "+alias+".Flush();")
	ast.Inspect(main.Body, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok || len(call.Args) != 1 {
			return true
		}
		callee := call.Fun
		for {
			paren, ok := callee.(*ast.ParenExpr)
			if !ok {
				break
			}
			callee = paren.X
		}
		exit := false
		switch fn := callee.(type) {
		case *ast.SelectorExpr:
			pkg, ok := fn.X.(*ast.Ident)
			exit = ok && pkg.Obj == nil && imports[pkg.Name] && fn.Sel.Name == "Exit"
		case *ast.Ident:
			exit = dotOS && fn.Obj == nil && fn.Name == "Exit"
		}
		if !exit {
			return true
		}
		// Pass the original exit function rather than wrapping its argument. This
		// saves at actual execution time for defer/go calls, and keeps the os import
		// used without introducing a closure or changing argument evaluation.
		start, end := file.Offset(call.Fun.Pos()), file.Offset(call.Fun.End())
		original := string(src[start:end])
		edits = append(edits, testMainEdit{start, end, alias + ".Exit"})
		insert(call.Lparen+1, original+",")
		return true
	})
	return applyTestMainEdits(src, edits), true, nil
}

// hasTestMainSignature follows cmd/go's isTestFunc, including unnamed parameters,
// import aliases, and dot imports. Aliases whose name isn't T or M are not
// accepted merely because they resolve to the corresponding testing type.
func hasTestMainSignature(fn *ast.FuncDecl, name string) bool {
	if fn.Type.Results.NumFields() > 0 || fn.Type.Params.NumFields() != 1 {
		return false
	}
	ptr, ok := fn.Type.Params.List[0].Type.(*ast.StarExpr)
	if !ok {
		return false
	}
	switch typ := ptr.X.(type) {
	case *ast.Ident:
		return typ.Name == name
	case *ast.SelectorExpr:
		return typ.Sel.Name == name
	}
	return false
}

func applyTestMainEdits(src []byte, edits []testMainEdit) []byte {
	sort.SliceStable(edits, func(i, j int) bool { return edits[i].start < edits[j].start })
	var out bytes.Buffer
	pos := 0
	for _, e := range edits {
		out.Write(src[pos:e.start])
		out.WriteString(e.text)
		pos = e.end
	}
	out.Write(src[pos:])
	return out.Bytes()
}
